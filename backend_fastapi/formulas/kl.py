# -*- coding: utf-8 -*-
"""筹码博弈 **KL** 的**计算层** —— 指标与策略共用的单一来源。

位于**中立内核包** `formulas/`（见该包 `__init__.py`）：它既不是指标、也不是策略、
更不是筹码 —— 只是「一段被两处复用的纯计算」。

通达信原式：

    KL:100*(WINNER(CLOSE)-WINNER(OPEN));

`WINNER(价)` = 筹码分布里「成本低于该价」的占比（获利盘比例）。于是 KL 看的是
**同一天内**，以开盘价和收盘价两个分界切出来的获利盘比例差：

  * KL > 0：收盘时的获利盘比开盘时多 → 当日**买盘占优**（筹码整体上移）
  * KL < 0：收盘时的获利盘比开盘时更少 → 当日**卖压占优**
  * |KL| 越过 ±80：**博弈剧烈**（多空分歧大 / 方向选择强烈）

⚠️ **量纲（别改错，这里踩过坑）**：通达信的 `WINNER` 返回 **0~1 的小数**，
所以原式 `KL = 100*(WINNER(C)-WINNER(O))` 的量程是 **±100**，
阈值 ±80 落在量程 80% 的位置 = 「接近极端」才有意义。
而本项目的筹码矩阵每行合计 100（**百分数**），直接拿它当小数用会把 KL
放大 100 倍（实测能到几千）—— 阈值线会被压到 0 附近，整张图没法看。
所以这里走 `winner_fraction`（通达信的小数口径），不是 `winner_series`。

换句话说：**KL 的单位是「获利盘比例变动了多少个百分点」**——
获利盘比例当天从 40% 变到 52%，KL 就是 +12。

## 物理含义（决定阈值该怎么理解）

KL 的大小 = **开盘价与收盘价之间那段价格区间里堆积的筹码占比 × 100**。
所以：

  * KL 大 → 当日振幅大到「八成筹码都挤在当日区间里」→ 只在暴涨/暴跌日出现；
  * KL > 80 是**极端事件**（实测：150 只票 × 2 年 = 72640 个交易日里只出现 3 天），
    拿它当「入池」门槛 = 一年可能只有几次信号。

口径要点：
  * 筹码矩阵与价格**同复权口径**（都是前复权 qfq），由调用方保证 ——
    拿 hfq 价格切 qfq 筹码，**错位不报错**，只会让数字看起来合理而已。
  * `WINNER` 的分界口径（严格小于）与指标 `WIN`（筹码获利比例）**完全一致** ——
    两者都走 `formulas/winner.py` 同一份内核，所以「博弈强度」与「获利盘」对得上号。
"""
from __future__ import annotations

import numpy as np

from .winner import winner_fraction

# 通达信把 WINNER 的「0~1 小数差」乘 100 → 量程 ±100
KL_SCALE = 100.0


def kl_series(matrix, centers, opens, closes) -> np.ndarray:
    """筹码博弈 KL（量程 ±100）。

    参数：
      matrix   筹码分布矩阵，形状 (帧数, 分箱数)；**每行合计 100**（%）。
      centers  各分箱的**价格中心**，长度 = 分箱数（升序）。
      opens    每帧的开盘价（与筹码矩阵**同复权口径**）。
      closes   每帧的收盘价（同上）。

    返回：长度 = 帧数的 float 数组；该帧无筹码数据或价格非有限时为 NaN。
    """
    wc = winner_fraction(matrix, centers, closes)
    wo = winner_fraction(matrix, centers, opens)
    return KL_SCALE * (wc - wo)
